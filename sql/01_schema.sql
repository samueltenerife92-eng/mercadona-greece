
-- Mercadona Greece: Database Schema
-- PostgreSQL
-- Creates the relational tables required by the analysis scripts.

CREATE TABLE IF NOT EXISTS cities (
    city_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(100) NOT NULL UNIQUE,
    region VARCHAR(100),
    population BIGINT,
    population_year INTEGER,
    data_status VARCHAR(50) NOT NULL DEFAULT 'pending_verification'
);

CREATE TABLE IF NOT EXISTS competitors (
    competitor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competitor_name VARCHAR(150) NOT NULL UNIQUE,
    market_positioning VARCHAR(150),
    website TEXT
);

CREATE TABLE IF NOT EXISTS stores (
    store_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name VARCHAR(150) NOT NULL,
    city_id INTEGER NOT NULL REFERENCES cities(city_id),
    competitor_id INTEGER NOT NULL REFERENCES competitors(competitor_id),
    store_type VARCHAR(100),
    area_sqm NUMERIC(12,2),
    data_status VARCHAR(50) NOT NULL DEFAULT 'pending_verification',
    address TEXT,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    source_url TEXT,
    verification_date DATE,
    data_notes TEXT
);

CREATE TABLE IF NOT EXISTS market_data (
    market_data_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id INTEGER NOT NULL REFERENCES cities(city_id),
    year INTEGER NOT NULL,
    average_monthly_household_income NUMERIC(12,2),
    estimated_monthly_grocery_spend NUMERIC(12,2),
    target_population BIGINT,
    data_status VARCHAR(50) NOT NULL DEFAULT 'pending_verification',
    target_households BIGINT,
    monthly_grocery_spend_per_household NUMERIC(12,2),
    estimated_monthly_rent NUMERIC(12,2),
    food_spend_data_level VARCHAR(100),
    food_spend_source TEXT,
    UNIQUE (city_id, year)
);

CREATE TABLE IF NOT EXISTS data_sources (
    source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name VARCHAR(200) NOT NULL,
    source_url TEXT,
    dataset_name VARCHAR(200),
    access_date DATE,
    notes TEXT
);

CREATE TABLE IF NOT EXISTS store_business_scenarios (
    scenario_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id INTEGER NOT NULL REFERENCES cities(city_id),
    scenario_name VARCHAR(50) NOT NULL,
    market_capture_rate NUMERIC(6,4) NOT NULL,
    monthly_rent NUMERIC(12,2) NOT NULL,
    monthly_staff_cost NUMERIC(12,2) NOT NULL,
    monthly_logistics_cost NUMERIC(12,2) NOT NULL,
    monthly_other_operating_cost NUMERIC(12,2) NOT NULL,
    gross_margin_rate NUMERIC(6,4) NOT NULL,
    notes TEXT
);
